/**
 * Recruitment module schema. Shared by the seed script and the incremental
 * migration so a fresh database and an upgraded database stay identical.
 *
 * Existing HR tables are referenced, never recreated.
 */

export const RECRUITMENT_TABLES = [
  'recruitment_activity_logs',
  'recruitment_offers',
  'recruitment_interview_feedback',
  'recruitment_interviews',
  'recruitment_applications',
  'recruitment_candidates',
  'recruitment_jobs',
];

export const RECRUITMENT_SCHEMA = [
  `CREATE TABLE IF NOT EXISTS recruitment_jobs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    job_code VARCHAR(30) NOT NULL UNIQUE,
    title VARCHAR(150) NOT NULL,
    department_id INT NULL,
    employment_type ENUM('full-time','part-time','contract','intern') NOT NULL DEFAULT 'full-time',
    work_location VARCHAR(150) NULL,
    work_mode ENUM('on-site','remote','hybrid') NOT NULL DEFAULT 'on-site',
    experience_min DECIMAL(4,1) NOT NULL DEFAULT 0,
    experience_max DECIMAL(4,1) NULL,
    salary_min DECIMAL(12,2) NULL,
    salary_max DECIMAL(12,2) NULL,
    vacancies INT NOT NULL DEFAULT 1,
    description TEXT NULL,
    responsibilities TEXT NULL,
    qualifications TEXT NULL,
    skills TEXT NULL,
    application_deadline DATE NULL,
    status ENUM('draft','open','on-hold','closed') NOT NULL DEFAULT 'draft',
    created_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_rjob_dept (department_id),
    INDEX idx_rjob_status (status),
    INDEX idx_rjob_deadline (application_deadline),
    CONSTRAINT fk_rjob_dept FOREIGN KEY (department_id) REFERENCES hrm_departments(id) ON DELETE SET NULL,
    CONSTRAINT fk_rjob_user FOREIGN KEY (created_by) REFERENCES hrm_users(id) ON DELETE SET NULL
  )`,

  `CREATE TABLE IF NOT EXISTS recruitment_candidates (
    id INT AUTO_INCREMENT PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(40) NULL,
    alternate_phone VARCHAR(40) NULL,
    location VARCHAR(150) NULL,
    highest_qualification VARCHAR(150) NULL,
    total_experience DECIMAL(4,1) NOT NULL DEFAULT 0,
    current_company VARCHAR(150) NULL,
    current_designation VARCHAR(150) NULL,
    expected_salary DECIMAL(12,2) NULL,
    notice_period VARCHAR(60) NULL,
    skills TEXT NULL,
    resume_file VARCHAR(255) NULL,
    resume_original_name VARCHAR(255) NULL,
    resume_mime VARCHAR(120) NULL,
    linkedin_url VARCHAR(300) NULL,
    portfolio_url VARCHAR(300) NULL,
    source VARCHAR(60) NOT NULL DEFAULT 'direct',
    created_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_rcand_email (email),
    INDEX idx_rcand_source (source),
    CONSTRAINT fk_rcand_user FOREIGN KEY (created_by) REFERENCES hrm_users(id) ON DELETE SET NULL
  )`,

  `CREATE TABLE IF NOT EXISTS recruitment_applications (
    id INT AUTO_INCREMENT PRIMARY KEY,
    job_id INT NOT NULL,
    candidate_id INT NOT NULL,
    stage ENUM('applied','screening','shortlisted','interview_scheduled','interview_completed','selected','offer_sent','hired','rejected') NOT NULL DEFAULT 'applied',
    rejection_reason TEXT NULL,
    recruiter_notes TEXT NULL,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    stage_updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    converted_employee_id INT NULL,
    converted_at DATETIME NULL,
    converted_by INT NULL,
    created_by INT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_rapp_job_candidate (job_id, candidate_id),
    INDEX idx_rapp_stage (stage),
    INDEX idx_rapp_job (job_id),
    INDEX idx_rapp_candidate (candidate_id),
    CONSTRAINT fk_rapp_job FOREIGN KEY (job_id) REFERENCES recruitment_jobs(id) ON DELETE CASCADE,
    CONSTRAINT fk_rapp_candidate FOREIGN KEY (candidate_id) REFERENCES recruitment_candidates(id) ON DELETE CASCADE,
    CONSTRAINT fk_rapp_employee FOREIGN KEY (converted_employee_id) REFERENCES hrm_employees(id) ON DELETE SET NULL,
    CONSTRAINT fk_rapp_user FOREIGN KEY (created_by) REFERENCES hrm_users(id) ON DELETE SET NULL
  )`,

  `CREATE TABLE IF NOT EXISTS recruitment_interviews (
    id INT AUTO_INCREMENT PRIMARY KEY,
    application_id INT NOT NULL,
    interviewer_id INT NULL,
    scheduled_at DATETIME NOT NULL,
    duration_minutes INT NOT NULL DEFAULT 60,
    interview_type ENUM('technical','hr','managerial','final') NOT NULL DEFAULT 'technical',
    mode ENUM('online','offline','phone') NOT NULL DEFAULT 'online',
    meeting_link VARCHAR(500) NULL,
    location VARCHAR(255) NULL,
    status ENUM('scheduled','completed','cancelled','rescheduled') NOT NULL DEFAULT 'scheduled',
    notes TEXT NULL,
    created_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_rint_schedule (scheduled_at),
    INDEX idx_rint_status (status),
    INDEX idx_rint_application (application_id),
    CONSTRAINT fk_rint_application FOREIGN KEY (application_id) REFERENCES recruitment_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_rint_interviewer FOREIGN KEY (interviewer_id) REFERENCES hrm_users(id) ON DELETE SET NULL,
    CONSTRAINT fk_rint_user FOREIGN KEY (created_by) REFERENCES hrm_users(id) ON DELETE SET NULL
  )`,

  `CREATE TABLE IF NOT EXISTS recruitment_interview_feedback (
    id INT AUTO_INCREMENT PRIMARY KEY,
    interview_id INT NOT NULL,
    technical_rating TINYINT NULL,
    communication_rating TINYINT NULL,
    problem_solving_rating TINYINT NULL,
    overall_rating TINYINT NULL,
    strengths TEXT NULL,
    weaknesses TEXT NULL,
    notes TEXT NULL,
    recommendation ENUM('strong_hire','hire','hold','reject') NOT NULL,
    submitted_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_rfb_interview (interview_id),
    CONSTRAINT fk_rfb_interview FOREIGN KEY (interview_id) REFERENCES recruitment_interviews(id) ON DELETE CASCADE,
    CONSTRAINT fk_rfb_user FOREIGN KEY (submitted_by) REFERENCES hrm_users(id) ON DELETE SET NULL
  )`,

  `CREATE TABLE IF NOT EXISTS recruitment_offers (
    id INT AUTO_INCREMENT PRIMARY KEY,
    application_id INT NOT NULL,
    offer_number VARCHAR(40) NOT NULL UNIQUE,
    job_title VARCHAR(150) NOT NULL,
    department_id INT NULL,
    annual_salary DECIMAL(12,2) NOT NULL DEFAULT 0,
    salary_structure TEXT NULL,
    joining_date DATE NULL,
    probation_months INT NOT NULL DEFAULT 3,
    employment_type ENUM('full-time','part-time','contract','intern') NOT NULL DEFAULT 'full-time',
    expiry_date DATE NULL,
    terms TEXT NULL,
    status ENUM('draft','sent','accepted','rejected','expired','withdrawn') NOT NULL DEFAULT 'draft',
    sent_at DATETIME NULL,
    responded_at DATETIME NULL,
    response_notes TEXT NULL,
    created_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_roff_status (status),
    INDEX idx_roff_application (application_id),
    CONSTRAINT fk_roff_application FOREIGN KEY (application_id) REFERENCES recruitment_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_roff_dept FOREIGN KEY (department_id) REFERENCES hrm_departments(id) ON DELETE SET NULL,
    CONSTRAINT fk_roff_user FOREIGN KEY (created_by) REFERENCES hrm_users(id) ON DELETE SET NULL
  )`,

  `CREATE TABLE IF NOT EXISTS recruitment_activity_logs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    job_id INT NULL,
    candidate_id INT NULL,
    application_id INT NULL,
    actor_id INT NULL,
    actor_name VARCHAR(100) NULL,
    action VARCHAR(80) NOT NULL,
    details JSON NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_ract_created (created_at),
    INDEX idx_ract_application (application_id),
    INDEX idx_ract_action (action),
    CONSTRAINT fk_ract_job FOREIGN KEY (job_id) REFERENCES recruitment_jobs(id) ON DELETE SET NULL,
    CONSTRAINT fk_ract_candidate FOREIGN KEY (candidate_id) REFERENCES recruitment_candidates(id) ON DELETE SET NULL,
    CONSTRAINT fk_ract_application FOREIGN KEY (application_id) REFERENCES recruitment_applications(id) ON DELETE SET NULL
  )`,
];
