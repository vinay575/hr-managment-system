import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import multer from 'multer';
import { fileURLToPath } from 'node:url';
import { ApiError } from './utils.js';

const here = path.dirname(fileURLToPath(import.meta.url));
export const UPLOAD_DIR = path.resolve(here, '../uploads/resumes');

fs.mkdirSync(UPLOAD_DIR, { recursive: true });

const ALLOWED = new Map([
  ['application/pdf', '.pdf'],
  ['application/msword', '.doc'],
  ['application/vnd.openxmlformats-officedocument.wordprocessingml.document', '.docx'],
]);

const storage = multer.diskStorage({
  destination: (req, file, cb) => cb(null, UPLOAD_DIR),
  filename: (req, file, cb) => {
    const ext = ALLOWED.get(file.mimetype) || path.extname(file.originalname).toLowerCase();
    cb(null, `${Date.now()}-${crypto.randomBytes(8).toString('hex')}${ext}`);
  },
});

export const resumeUpload = multer({
  storage,
  limits: { fileSize: 5 * 1024 * 1024, files: 1 },
  fileFilter: (req, file, cb) => {
    if (!ALLOWED.has(file.mimetype)) {
      return cb(new ApiError(400, 'Resume must be a PDF, DOC or DOCX file.'));
    }
    cb(null, true);
  },
}).single('resume');

/** Wrap multer so its errors become normal ApiErrors handled by the app. */
export function uploadResume(req, res, next) {
  resumeUpload(req, res, (err) => {
    if (!err) return next();
    if (err instanceof ApiError) return next(err);
    if (err.code === 'LIMIT_FILE_SIZE') return next(new ApiError(400, 'Resume must be 5 MB or smaller.'));
    return next(new ApiError(400, err.message || 'Could not upload the resume.'));
  });
}

export function resumePath(storedName) {
  // Stored names are generated by us; guard against any traversal attempt.
  const safe = path.basename(String(storedName || ''));
  const full = path.join(UPLOAD_DIR, safe);
  if (!full.startsWith(UPLOAD_DIR)) throw new ApiError(400, 'Invalid resume path.');
  return full;
}

export function removeResume(storedName) {
  if (!storedName) return;
  try {
    const full = resumePath(storedName);
    if (fs.existsSync(full)) fs.unlinkSync(full);
  } catch {
    /* best effort */
  }
}
